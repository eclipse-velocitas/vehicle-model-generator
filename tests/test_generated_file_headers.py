import compileall
from pathlib import Path

from vss_tools.tree import VSSNode  # type: ignore

from velocitas.model_generator.cpp.cpp_generator import VehicleModelCppGenerator
from velocitas.model_generator.python.python_generator import (
    VehicleModelPythonGenerator,
)


CPP_HEADER_LINE = (
    "// This code was generated by the Eclipse Velocitas Vehicle Model " "Generator"
)
PYTHON_HEADER_LINE = (
    "# This code was generated by the Eclipse Velocitas Vehicle Model Generator"
)


def test_cpp_generated_files_start_with_generic_header(tmp_path: Path):
    root_node = VSSNode(
        name="Vehicle",
        fqn="Vehicle",
        data={"type": "branch", "description": "Vehicle root"},
    )
    cabin_node = VSSNode(
        name="Cabin",
        fqn="Vehicle.Cabin",
        data={"type": "branch", "description": "Vehicle cabin"},
    )
    cabin_node.parent = root_node
    root_node.children = [cabin_node]
    output_path = tmp_path / "cpp"
    output_path.mkdir()

    VehicleModelCppGenerator(root_node, str(output_path), "vehicle").generate()

    generated_headers = [
        output_path / "include" / "vehicle" / "Vehicle.hpp",
        output_path / "include" / "vehicle" / "cabin" / "Cabin.hpp",
    ]
    generated_conanfile = (output_path / "conanfile.py").read_text()

    assert all(
        path.read_text().startswith(CPP_HEADER_LINE) for path in generated_headers
    )
    assert generated_conanfile.startswith("from conan import ConanFile")


def test_python_generated_files_start_with_generic_header(tmp_path: Path):
    root_node = VSSNode(
        name="Vehicle",
        fqn="Vehicle",
        data={"type": "branch", "description": "Vehicle root"},
    )
    cabin_node = VSSNode(
        name="Cabin",
        fqn="Vehicle.Cabin",
        data={"type": "branch", "description": "Vehicle cabin"},
    )
    cabin_node.parent = root_node
    root_node.children = [cabin_node]
    output_path = tmp_path / "python"
    output_path.mkdir()

    VehicleModelPythonGenerator(root_node, str(output_path), "vehicle").generate()

    generated_module = (output_path / "vehicle" / "__init__.py").read_text()
    generated_nested_module = (
        output_path / "vehicle" / "Cabin" / "__init__.py"
    ).read_text()
    generated_setup = (output_path / "setup.py").read_text()

    assert generated_module.startswith("#!/usr/bin/env python3\n")
    assert PYTHON_HEADER_LINE in generated_module.splitlines()[1]
    assert generated_nested_module.startswith("#!/usr/bin/env python3\n")
    assert PYTHON_HEADER_LINE in generated_nested_module.splitlines()[1]
    assert generated_setup.startswith(PYTHON_HEADER_LINE)
    assert compileall.compile_dir(str(output_path), quiet=1)
